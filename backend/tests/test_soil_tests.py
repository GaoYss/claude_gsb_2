def test_backfill_actual_amount_computes_deviation(api, make_fertilization):
    application = make_fertilization(planned_area=2000)
    planned = float(application.planned_amount)

    data = api.data(api.put(f"/api/v1/fertilizations/{application.id}", {
        "soil_test_id": application.soil_test_id,
        "plan_date": "2026-03-20",
        "planned_area": 2000,
        "status": "applied",
        "applied_date": "2026-03-21",
        "actual_dosage": 0.06,
        "actual_area": 2000,
        "worker": "王海涛",
        "work_hours": 8,
    }))
    assert data["status"] == "applied"
    assert data["actual_amount"] == 120.0
    assert data["deviation"] == round(120.0 - planned, 2)

    # 检测档案详情能看到回填的施肥作业与累计实际用量
    detail = api.data(api.get(f"/api/v1/soil-tests/{application.soil_test_id}"))
    assert detail["application_count"] == 1
    assert detail["total_applied_amount"] == 120.0
    assert detail["applications"][0]["actual_amount"] == 120.0


def test_fertilization_summary_and_filters(api, make_fertilization):
    applied = make_fertilization(planned_area=1000, status="applied",
                                 applied_date=date(2026, 3, 22),
                                 actual_dosage=0.06, actual_area=1000)
    make_fertilization(planned_area=500)

    summary = api.data(api.get("/api/v1/fertilizations/summary"))
    assert summary["total_count"] == 2
    assert summary["applied_count"] == 1
    assert summary["planned_count"] == 1
    assert summary["actual_amount"] == 60.0

    data = api.data(api.get("/api/v1/fertilizations", status="applied"))
    assert data["meta"]["total"] == 1
    assert data["items"][0]["id"] == applied.id



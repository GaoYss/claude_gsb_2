def test_custom_formula_is_kept_and_missing_formula_autogenerated(api, make_space):
    space = make_space(green_type="road")

    # 不提供配方 -> 系统按缺素与绿地类型自动生成
    auto = api.data(api.post("/api/v1/soil-tests", soil_payload(space.id)), 201)
    assert auto["fertilizer_type"]
    assert auto["fertilizer_name"]
    assert auto["dosage_per_sqm"] > 0
    assert auto["application_method_label"]
    assert "施肥" in auto["formula_advice"]

    # 手工提供配方 -> 原样保留
    custom = api.data(api.post("/api/v1/soil-tests", soil_payload(
        space.id, report_no="TR-CUSTOM", fertilizer_type="organic",
        fertilizer_name="腐熟羊粪", nutrient_ratio="有机质≥45%",
        dosage_per_sqm=2.0, application_frequency="每年 1 次",
        application_method="broadcast", application_period="秋季",
        formula_advice="结合秋施基肥改土",
    )), 201)
    assert custom["fertilizer_type"] == "organic"
    assert custom["fertilizer_name"] == "腐熟羊粪"
    assert custom["dosage_per_sqm"] == 2.0
    assert custom["formula_advice"] == "结合秋施基肥改土"


def test_regenerate_plan_overwrites_formula(api, make_space):
    space = make_space()
    created = api.data(api.post("/api/v1/soil-tests", soil_payload(
        space.id, fertilizer_type="organic", fertilizer_name="自定义肥料",
    )), 201)
    assert created["fertilizer_name"] == "自定义肥料"

    regenerated = api.data(api.post(f"/api/v1/soil-tests/{created['id']}/regenerate-plan"))
    assert regenerated["fertilizer_type"]
    assert regenerated["fertilizer_name"] != "自定义肥料"


def test_list_filter_and_summary(api, make_space):
    space = make_space()
    other = make_space(name="其他绿地")
    api.post("/api/v1/soil-tests", soil_payload(space.id, ph_value=4.8))
    api.post("/api/v1/soil-tests", soil_payload(space.id, sample_date="2026-05-01",
                                                report_no="TR-2", ph_value=7.2))
    api.post("/api/v1/soil-tests", soil_payload(other.id, report_no="TR-3"))

    data = api.data(api.get("/api/v1/soil-tests", green_space_id=space.id))
    assert data["meta"]["total"] == 2

    data = api.data(api.get("/api/v1/soil-tests", ph_level="strong_acid"))
    assert data["meta"]["total"] == 1

    summary = api.data(api.get("/api/v1/soil-tests/summary"))
    assert summary["total_count"] == 3
    assert summary["green_space_count"] == 2
    assert summary["abnormal_ph_count"] == 1


def test_comparison_returns_history_in_date_order(api, make_space):
    space = make_space()
    api.post("/api/v1/soil-tests", soil_payload(space.id, sample_date="2026-03-01",
                                                ph_value=5.6, organic_matter=15.0))
    api.post("/api/v1/soil-tests", soil_payload(space.id, sample_date="2026-09-01",
                                                report_no="TR-2", ph_value=6.9, organic_matter=26.0))

    data = api.data(api.get("/api/v1/soil-tests/comparison", green_space_id=space.id))
    assert data["green_space"]["id"] == space.id
    assert [item["sample_date"] for item in data["items"]] == ["2026-03-01", "2026-09-01"]
    assert [item["ph_value"] for item in data["items"]] == [5.6, 6.9]
    assert [item["organic_matter"] for item in data["items"]] == [15.0, 26.0]



def test_deleting_green_space_blocks_with_soil_test(api, make_soil_test):
    test = make_soil_test()
    space_id = test.green_space_id

    response = api.delete(f"/api/v1/green-spaces/{space_id}")
    assert response.status_code == 409
    assert response.get_json()["data"]["soil_test"] == 1

    api.delete(f"/api/v1/green-spaces/{space_id}", force="true")
    assert api.get(f"/api/v1/soil-tests/{test.id}").status_code == 404



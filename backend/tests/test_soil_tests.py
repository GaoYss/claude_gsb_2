# ---------------------------------------------------------------- 施肥作业
def test_create_application_inherits_formula(api, make_soil_test):
    test = make_soil_test()
    data = api.data(api.post("/api/v1/fertilizations", {
        "soil_test_id": test.id,
        "plan_date": "2026-03-20",
        "planned_area": 2000,
        "executor": "绿化二班",
    }), 201)
    assert data["application_no"].startswith("FA-")
    assert data["green_space_id"] == test.green_space_id
    assert data["fertilizer_name"] == test.fertilizer_name
    # 建议用量 0.05kg/㎡（park 默认）× 2000㎡
    assert data["planned_dosage"] == float(test.dosage_per_sqm)
    assert data["planned_amount"] == round(2000 * float(test.dosage_per_sqm), 2)
    assert data["status"] == "planned"
    assert data["status_label"] == "待执行"



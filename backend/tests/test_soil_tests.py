"""土壤检测档案与施肥作业接口测试。"""

from datetime import date


def soil_payload(space_id, **overrides):
    payload = {
        "green_space_id": space_id,
        "sample_date": "2026-03-01",
        "sample_point": "中央草坪 5 点混合样",
        "sample_depth": 20,
        "lab_org": "市园林科学研究所检测中心",
        "report_no": "TR-2026-0312",
        "soil_texture": "loam",
        "ph_value": 6.8,
        "organic_matter": 18.5,
        "alkali_nitrogen": 86.0,
        "available_phosphorus": 12.4,
        "available_potassium": 132.0,
        "bulk_density": 1.32,
        "moisture": 22.5,
        "target_plants": "马尼拉草坪、金森女贞",
    }
    payload.update(overrides)
    return payload


# ---------------------------------------------------------------- 检测档案
def test_create_soil_test_generates_code_and_grades(api, make_space):
    space = make_space()
    data = api.data(api.post("/api/v1/soil-tests", soil_payload(space.id)), 201)
    assert data["test_no"].startswith("ST-")
    assert data["ph_value"] == 6.8
    assert data["ph_level"] == "neutral"
    assert data["ph_level_label"] == "中性"
    assert data["organic_level"] == "low"
    assert data["nitrogen_level"] == "low"
    assert data["phosphorus_level"] == "low"
    assert data["potassium_level"] == "medium"
    assert data["soil_texture_label"] == "壤土"


def test_strong_acid_and_nutrient_lack_are_graded(api, make_space):
    space = make_space()
